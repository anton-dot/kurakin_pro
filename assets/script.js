const fallbackLang = "ru";
const storageKey = "kurakin-site-lang";

const getNestedValue = (source, path) =>
  path.split(".").reduce((value, key) => value?.[key], source);

const normalizeLang = (value) =>
  value?.trim().toLowerCase().split("-")[0];

const getInitialLang = () => {
  const pageLang = normalizeLang(document.body.dataset.lang);
  if (pageLang && languages[pageLang]) {
    return pageLang;
  }

  const params = new URLSearchParams(window.location.search);
  const candidates = [
    params.get("lang"),
    window.localStorage.getItem(storageKey),
    ...(navigator.languages ?? []),
    navigator.language,
    fallbackLang,
  ].map(normalizeLang);

  return candidates.find((lang) => lang && languages[lang]) ?? fallbackLang;
};

