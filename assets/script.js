const renderNumberedItems = (selector, items, itemClass) => {
  const root = document.querySelector(selector);
  if (!root) {
    return;
  }

  root.replaceChildren(
    ...items.map((item, index) => {
      const article = createElement("article", itemClass);
      const content = createElement("div", `${itemClass}-content`);
      content.append(createElement("h3", "", item.title), createElement("p", "", item.text));
      article.append(
        createElement("span", `${itemClass}-index`, String(index + 1).padStart(2, "0")),
        content,
      );
      return article;
    }),
  );
};

